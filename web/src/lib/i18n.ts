export type Dictionary = (typeof dict)["vi"] | (typeof dict)["en"];

export function getDict(locale: string): Dictionary {
  return locale === "en" ? dict.en : dict.vi;
}

export function isLocale(v: string): v is Locale {
  return v === "vi" || v === "en";
}

/** Replace `{key}` placeholders in dictionary templates. */
export function tFormat(template: string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce(
    (out, [key, value]) => out.replaceAll(`{${key}}`, String(value)),
    template,
  );
}

export function localeTag(locale: string): string {
  return locale === "en" ? "en-US" : "vi-VN";
}
